// Minimum tool versions (checked at startup).
const (
	MinExiftool = 12.70
	MinFFmpeg   = 6
)

// DefaultTimeout bounds each tool call and fetch when no timeout is set.
const DefaultTimeout = 120 * time.Second

// Runner runs exiftool and ffmpeg. Every process gets an empty environment
// and a working directory inside TmpDir, and every call is bounded by
// Timeout. exiftool runs on pooled -stay_open processes; ffmpeg gets a new
// process with closed stdin per call. Paths passed to the tools are
// generated by the cache, never taken from Immich. The zero value with
// the fields set is ready to use; don't copy a Runner.
type Runner struct {
	Exiftool string // default "exiftool"
	FFmpeg   string // default "ffmpeg"
	TmpDir   string
	Timeout  time.Duration // default DefaultTimeout
	// Workers is how many idle exiftool processes are kept (default: CPUs).
	Workers int

	mu     sync.Mutex
	pool   *exifPool
	closed bool
}

func (r *Runner) exifPool() (*exifPool, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.closed {
		return nil, errRunnerClosed
	}
	if r.pool == nil {
		workers := r.Workers
		if workers <= 0 {
			workers = runtime.NumCPU()
		}
		r.pool = &exifPool{path: r.exiftool(), dir: r.TmpDir, maxIdle: workers}
	}
	return r.pool, nil
}

// Close stops the idle exiftool processes; later exiftool calls fail.
func (r *Runner) Close() {
	r.mu.Lock()
	r.closed = true
	p := r.pool
	r.mu.Unlock()
	if p != nil {
		p.close()
	}
}

func (r *Runner) exiftool() string {
	if r.Exiftool != "" {
		return r.Exiftool
	}
	if p, err := LookTool("exiftool"); err == nil {
		return p
	}
	return "exiftool"
}

func (r *Runner) ffmpeg() string {
	if r.FFmpeg != "" {
		return r.FFmpeg
	}
	if p, err := LookTool("ffmpeg"); err == nil {
		return p
	}
	return "ffmpeg"
}

func (r *Runner) timeout() time.Duration {
	if r.Timeout <= 0 {
		return DefaultTimeout
	}
	return r.Timeout
}

// exif runs one exiftool command on a pooled process and returns its
// stdout, with the same errors as run.
func (r *Runner) exif(ctx context.Context, args ...string) ([]byte, error) {
	for _, a := range args {
		if !validArg(a) {
			return nil, ToolError{Kind: ToolCrash, Err: fmt.Errorf("exiftool: bad argument %q", a)}
		}
	}
	ctx, cancel := context.WithTimeout(ctx, r.timeout())
	defer cancel()
	p, err := r.exifPool()
	if err != nil {
		return nil, ToolError{Kind: ToolCrash, Err: fmt.Errorf("exiftool: %w", err)}
	}
	w, err := p.get()
	if err != nil {
		return nil, ToolError{Kind: ToolCrash, Err: fmt.Errorf("exiftool: %w", err)}
	}
	res, err := w.exec(ctx, args)
	if ctx.Err() != nil {
		w.kill()
		return nil, ToolError{Kind: ToolTimeout, Err: ctx.Err()}
	}
	if err != nil {
		w.kill()
		return nil, ToolError{Kind: ToolCrash, Err: fmt.Errorf("exiftool: %w", err)}
	}
	p.put(w)
	if res.status != 0 {
		return res.stdout, ToolError{Kind: ToolCrash, Err: fmt.Errorf("exiftool: exit status %d: %s", res.status, firstLine(res.stderr))}
	}
	return res.stdout, nil
}

// run executes a tool and returns its stdout.
func (r *Runner) run(ctx context.Context, name string, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, r.timeout())
	defer cancel()
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.Env = []string{}
	cmd.Dir = r.TmpDir
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	cmd.WaitDelay = 5 * time.Second
	err := cmd.Run()
	if ctx.Err() != nil {
		return nil, ToolError{Kind: ToolTimeout, Err: ctx.Err()}
	}
	if err != nil {
		var exitErr *exec.ExitError
		if errors.As(err, &exitErr) {
			return stdout.Bytes(), ToolError{Kind: ToolCrash, Err: fmt.Errorf("%s: %w: %s", filepath.Base(name), err, firstLine(stderr.String()))}
		}
		return nil, ToolError{Kind: ToolCrash, Err: err}
	}
	return stdout.Bytes(), nil
}

func firstLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 200 {
		s = s[:200]
	}
	return s
}

// CheckTools verifies exiftool and ffmpeg exist and meet the minimum versions.
func (r *Runner) CheckTools(ctx context.Context) (exiftoolVer, ffmpegVer string, err error) {
	out, err := r.run(ctx, r.exiftool(), "-ver")
	if err != nil {
		return "", "", fmt.Errorf("exiftool: %w", err)
	}
	exiftoolVer = strings.TrimSpace(string(out))
	if v, perr := strconv.ParseFloat(exiftoolVer, 64); perr != nil || v < MinExiftool {
		return "", "", fmt.Errorf("exiftool %s is older than %.2f", exiftoolVer, MinExiftool)
	}
	out, err = r.run(ctx, r.ffmpeg(), "-hide_banner", "-version")
	if err != nil {
		return "", "", fmt.Errorf("ffmpeg: %w", err)
	}
	m := ffmpegVersion.FindStringSubmatch(string(out))
	if m == nil {
		return "", "", fmt.Errorf("ffmpeg: unrecognised version %q", firstLine(string(out)))
	}
	ffmpegVer = m[1]
	if major, _ := strconv.Atoi(m[2]); major < MinFFmpeg && !strings.HasPrefix(ffmpegVer, "N-") {
		return "", "", fmt.Errorf("ffmpeg %s is older than %d", ffmpegVer, MinFFmpeg)
	}
	return exiftoolVer, ffmpegVer, nil
}

var ffmpegVersion = regexp.MustCompile(`ffmpeg version n?((\d+)[^\s]*|N-[^\s]+)`)

// Process applies op to the file at in and returns the outcome. On Verified
// the output is a new file in TmpDir; on any other outcome no output
// remains. The input file is left in place (the caller owns it).
func (r *Runner) Process(ctx context.Context, in string, op Op) Outcome {
	in, err := filepath.Abs(in)
	if err != nil {
		return ToolError{Kind: ToolCrash, Err: err}
	}
	kind, err := Sniff(in)
	if err != nil {
		return ToolError{Kind: ToolCrash, Err: err}
	}
	out, err := r.tempPath(kind, op)
	if err != nil {
		return ToolError{Kind: ToolCrash, Err: err}
	}
	switch op {
	case OpVerify:
		if kind == ContainerUnknown {
			return Rejected{Tags: []string{"File:UnknownFormat"}}
		}
		if err := copyFile(in, out); err != nil {
			return ToolError{Kind: ToolCrash, Err: err}
		}
	case OpStrip:
		if kind == ContainerUnknown || kind.IsVideo() {
			return Rejected{Tags: []string{"File:UnsupportedFormat"}}
		}
		// exiftool picks the output writer from extensions, so the input
		// must carry the extension of its sniffed kind.
		if !strings.EqualFold(filepath.Ext(in), "."+kind.Ext()) {
			staged, err := r.tempPath(kind, "in")
			if err == nil {
				err = copyFile(in, staged)
			}
			if err != nil {
				return ToolError{Kind: ToolCrash, Err: err}
			}
			defer func() { _ = os.Remove(staged) }()
			in = staged
		}
		args := []string{"-q", "-q"}
		// -fast2 skips parsing maker notes, which -all= drops anyway; verify
		// still reads everything. exiftool can't write PNG with it.
		if kind != ContainerPNG {
			args = append(args, "-fast2")
		}
		// -o refuses to overwrite, so out must not exist yet.
		args = append(args, "-all=", "-tagsFromFile", "@", "-ColorSpaceTags", "-Orientation", "-o", out, in)
		if _, err := r.exif(ctx, args...); err != nil {
			_ = os.Remove(out)
			return toolError(err)
		}
	case OpRemux:
		out = strings.TrimSuffix(out, filepath.Ext(out)) + ".mp4"
		_, err := r.run(ctx, r.ffmpeg(), "-nostdin", "-v", "error", "-y", "-i", in,
			"-map", "0:v:0", "-map", "0:a?", "-c", "copy",
			"-map_metadata", "-1", "-map_metadata:s:v", "-1", "-map_metadata:s:a", "-1", "-map_chapters", "-1",
			"-fflags", "+bitexact", "-flags:v", "+bitexact", "-flags:a", "+bitexact",
			"-movflags", "+faststart", "-f", "mp4", out)
		if err != nil {
			_ = os.Remove(out)
			return toolError(err)
		}
	default:
		return ToolError{Kind: ToolUnsupported, Err: fmt.Errorf("op %q", op)}
	}
	v, outcome := r.verify(ctx, out)
	if outcome != nil {
		_ = os.Remove(out)
		return outcome
	}
	return v
}

func toolError(err error) ToolError {
	var te ToolError
	if errors.As(err, &te) {
		return te
	}
	return ToolError{Kind: ToolCrash, Err: err}
}

// Reverify runs the verifier on an already committed file (cache entries
// rebuilt at startup) without changing it.
func (r *Runner) Reverify(ctx context.Context, path string) (Verified, error) {
	v, outcome := r.verify(ctx, path)
	if outcome != nil {
		return Verified{}, outcome.(error)
	}
	return v, nil
}

// verify checks the file at path: its structure, then every exiftool tag
// against the allowlist.
func (r *Runner) verify(ctx context.Context, path string) (Verified, Outcome) {
	path, err := filepath.Abs(path)
	if err != nil {
		return Verified{}, ToolError{Kind: ToolCrash, Err: err}
	}
	kind, err := Sniff(path)
	if err != nil {
		return Verified{}, ToolError{Kind: ToolCrash, Err: err}
	}
	if kind == ContainerUnknown {
		return Verified{}, Rejected{Tags: []string{"File:UnknownFormat"}}
	}
	if err := checkStructure(path, kind); err != nil {
		return Verified{}, Rejected{Tags: []string{"File:Structure(" + structureReason(err) + ")"}}
	}
	out, err := r.exif(ctx, "-j", "-a", "-u", "-G1", "-n", "-ee", path)
	if err != nil {
		var te ToolError
		if errors.As(err, &te) && te.Kind == ToolTimeout {
			return Verified{}, te
		}
		if len(out) == 0 {
			return Verified{}, ToolError{Kind: ToolCrash, Err: err}
		}
	}
	pairs, err := parseExiftoolJSON(out)
	if err != nil {
		return Verified{}, ToolError{Kind: ToolCrash, Err: err}
	}
	var bad []string
	byName := map[string]any{}
	for _, p := range pairs {
		if _, dup := byName[p.name]; dup {
			// Duplicate group:tag keys: check each value on its own.
			if b := checkTags(kind, map[string]any{p.name: p.value}); len(b) > 0 {
				bad = append(bad, b...)
			}
			continue
		}
		byName[p.name] = p.value
	}
	bad = append(bad, checkTags(kind, byName)...)
	if len(bad) > 0 {
		return Verified{}, Rejected{Tags: bad}
	}
	st, err := os.Stat(path)
	if err != nil {
		return Verified{}, ToolError{Kind: ToolCrash, Err: err}
	}
	return Verified{path: path, container: kind, size: st.Size()}, nil
}

// structureReason keeps structural failures free of file content.
func structureReason(err error) string {
	s := err.Error()
	if len(s) > 80 {
		s = s[:80]
	}
	return s
}

type tagPair struct {
	name  string
	value any
}

// parseExiftoolJSON reads exiftool's `-j` output for one file, keeping
// duplicate keys.
func parseExiftoolJSON(b []byte) ([]tagPair, error) {
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.UseNumber()
	expect := func(want json.Delim) error {
		tok, err := dec.Token()
		if err != nil {
			return err
		}
		if d, ok := tok.(json.Delim); !ok || d != want {
			return fmt.Errorf("exiftool json: want %q, got %v", want, tok)
		}
		return nil
	}
	if err := expect('['); err != nil {
		return nil, err
	}
	if err := expect('{'); err != nil {
		return nil, err
	}
	var out []tagPair
	for dec.More() {
		tok, err := dec.Token()
		if err != nil {
			return nil, err
		}
		key, ok := tok.(string)
		if !ok {
			return nil, fmt.Errorf("exiftool json: key %v", tok)
		}
		var val any
		if err := dec.Decode(&val); err != nil {
			return nil, err
		}
		out = append(out, tagPair{name: key, value: val})
	}
	if err := expect('}'); err != nil {
		return nil, err
	}
	if dec.More() {
		return nil, errors.New("exiftool json: more than one file")
	}
	return out, nil
}

func (r *Runner) tempPath(k Container, op Op) (string, error) {
	return TempName(r.TmpDir, "out-"+string(op)+"-*."+k.Ext())
}

// TempName returns a fresh path in dir that doesn't exist yet, for tools
// that refuse to overwrite (exiftool -o) and O_EXCL writers. pattern is as
// for os.CreateTemp.
func TempName(dir, pattern string) (string, error) {
	f, err := os.CreateTemp(dir, pattern)
	if err != nil {
		return "", err
	}
	name := f.Name()
	_ = f.Close()
	return name, os.Remove(name)
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		_ = out.Close()
		_ = os.Remove(dst)
		return err
	}
	return out.Close()
}

// LookTool finds a tool on PATH, skipping version-manager shims (mise,
// asdf) that don't run with the empty environment the runner uses.
func LookTool(name string) (string, error) {
	for _, dir := range filepath.SplitList(os.Getenv("PATH")) {
		if strings.Contains(dir, "/shims") {
			continue
		}
		p := filepath.Join(dir, name)
		//nolint:gosec // PATH lookup, not request input
		if st, err := os.Stat(p); err == nil && !st.IsDir() && st.Mode()&0o111 != 0 {
			return p, nil
		}
	}
	return exec.LookPath(name)
}
